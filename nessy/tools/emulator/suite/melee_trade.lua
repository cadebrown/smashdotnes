local h = dofile('nessy/tools/emulator/suite/quality_common.lua')

h.run(function()
  h.start()
  -- P2 starts on Simon; choose Mario so both jabs have identical startup.
  h.tap(2, 'Left')
  h.battle()
  h.pad(1, {'Right'})
  h.pad(2, {'Left'})
  assert(h.until_true(function() return h.rs16(14) - h.rs16(8) <= 24 end, 60, 'approach'), 'failed to stage contact')
  h.clear()
  h.tick(2)
  assert(h.rb(12) == 0 and h.rb(18) == 0, 'unexpected damage before trade')
  h.snapshot('01-contact')
  h.pad(1, {'A'})
  h.pad(2, {'A'})
  assert(h.until_true(function() return h.rb(24) > 0 and h.rb(27) > 0 end, 12, 'startup'), 'both jabs did not start')
  assert(h.rb(24) == h.rb(27), 'mirror jabs did not start together')
  local startup = h.rb(24)
  h.clear()
  assert(h.until_true(function() return h.rb(12) > 0 or h.rb(18) > 0 end, 12, 'contact'), 'neither jab connected')
  local damage1, damage2 = h.rb(12), h.rb(18)
  if damage1 ~= 6 or damage2 ~= 6 then
    h.tick(2, 'visible-failed-impact')
    h.snapshot('02-impact')
  end
  assert(damage1 == 6 and damage2 == 6, string.format('same-frame jabs must trade: P1 damage=%d P2 damage=%d startup=%d', damage1, damage2, startup))
  assert(h.rb(24) == 0 and h.rb(25) == 0 and h.rb(27) == 0 and h.rb(28) == 0, 'trade retained an action timer')
  assert(h.rb(26) > 0 and h.rb(29) > 0, 'both fighters must enter hitstun')
  assert((h.rb(31) >> 6) == 2, 'trade must present both impact effects')
  -- The export precedes the following OAM DMA; allow the impact to render.
  h.tick(2, 'visible-impact')
  h.snapshot('02-impact')
  h.tick(24, 'recovery')
  assert(h.rb(12) == damage1 and h.rb(18) == damage2, 'trade dealt repeated damage')
  assert(h.rb(26) == 0 and h.rb(29) == 0 and (h.rb(31) >> 6) == 0, 'trade did not recover')
  h.snapshot('03-recovery')
  return 'simultaneous Mario jabs traded 6 damage each, cancelled both actions, showed two sparks, and recovered without repeat hits'
end)
